import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { loadConfig } from '../server/config.ts';
import { createBoardServer } from '../server/app.ts';

export const BOARD_PASSWORD = 'correct horse battery staple';
export const SESSION_SECRET = 's'.repeat(48);
export const SYNTHETIC_TOKEN = 'ghp_synthetic_board_token_000000000000';

function allocateSessionFile() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'test-board-'));
  return path.join(dir, 'sessions.json');
}

function cleanupSessionStorage(sessionFile) {
  if (!sessionFile) return;
  try {
    const dir = path.dirname(sessionFile);
    if (path.basename(dir).startsWith('test-board-')) {
      fs.rmSync(dir, { recursive: true, force: true });
    } else if (fs.existsSync(sessionFile)) {
      fs.unlinkSync(sessionFile);
    }
  } catch {}
}

export function browserConfig(fake, env = {}) {
  const sessionFile = env.BOARD_SESSION_FILE ?? allocateSessionFile();
  return loadConfig({
    BOARD_GITHUB_TOKEN: fake.token,
    BOARD_GITHUB_LOGIN: fake.login,
    BOARD_REPO: fake.repo,
    BOARD_PASSWORD: BOARD_PASSWORD,
    BOARD_SESSION_SECRET: SESSION_SECRET,
    BOARD_SESSION_FILE: sessionFile,
    ...env,
  });
}

export async function startBoard(fake, options = {}) {
  const explicitSessionFile = options.sessionFilePath !== undefined
    ? options.sessionFilePath
    : options.env?.BOARD_SESSION_FILE;
  const autoGenerated = explicitSessionFile === undefined;
  const sessionFile = explicitSessionFile !== undefined
    ? explicitSessionFile
    : (options.config?.sessionFilePath || allocateSessionFile());
  const config = options.config ?? browserConfig(fake, { BOARD_SESSION_FILE: sessionFile, ...options.env });
  const logs = [];
  let app;
  try {
    app = await createBoardServer({
      config,
      githubApiBase: fake.url,
      logger: (line) => logs.push(line),
      sessionFilePath: sessionFile,
      ...options,
    });
  } catch (err) {
    if (autoGenerated && !options.preserveSessionFile) {
      cleanupSessionStorage(sessionFile);
    }
    throw err;
  }
  const originalClose = app.close.bind(app);
  app.close = async () => {
    try {
      await originalClose();
    } finally {
      if (autoGenerated && !options.preserveSessionFile) {
        cleanupSessionStorage(sessionFile);
      }
    }
  };
  const { port, host } = await app.listen(options.port ?? 0, options.host ?? config.host);
  const baseHost = host === '0.0.0.0' ? '127.0.0.1' : (host ?? '127.0.0.1');
  const base = `http://${baseHost}:${port}`;
  return { app, config, logs, url: base, port, host, sessionFile };
}

export class HttpSession {
  constructor(base) {
    this.base = base;
    this.cookie = null;
    this.csrf = null;
  }

  async request(path, { method = 'GET', body, csrf = true, headers = {} } = {}) {
    const requestHeaders = { ...headers };
    if (body !== undefined) requestHeaders['content-type'] = 'application/json';
    if (this.cookie) requestHeaders.cookie = this.cookie;
    if (csrf && this.csrf) requestHeaders['x-csrf-token'] = this.csrf;
    const response = await fetch(`${this.base}${path}`, {
      method,
      headers: requestHeaders,
      body: body === undefined ? undefined : JSON.stringify(body),
      redirect: 'manual',
    });
    const setCookie = response.headers.get('set-cookie');
    if (setCookie) {
      const cookiePair = setCookie.split(';')[0];
      this.cookie = cookiePair.endsWith('=') ? null : cookiePair;
      if (/Max-Age=0/i.test(setCookie)) this.cookie = null;
    }
    const text = await response.text();
    let json = null;
    try {
      json = text ? JSON.parse(text) : null;
    } catch {
      json = null;
    }
    return { status: response.status, headers: response.headers, text, json };
  }

  async login(password = BOARD_PASSWORD) {
    const response = await this.request('/api/session', {
      method: 'POST',
      body: { password },
      csrf: false,
    });
    if (response.status === 200) this.csrf = response.json.csrfToken;
    return response;
  }

  async logout() {
    return this.request('/api/session', { method: 'DELETE' });
  }
}
